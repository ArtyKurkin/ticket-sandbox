"""V1 future ports, no implementations, socket discovery or generic SDK access.

An adapter must call RAW create, return/sign exact ID before secondary inspect or
diagnostic I/O, and use authority fences for the fixed bounded mutations. The
runner receives only numeric IPv4/fixed policy/artifact inputs, never credentials.
"""

from typing import Protocol

from .attestation import Attestation
from .contracts import (AttemptReference, CreateIntent, DispatchPermit, OrdinaryMetadata,
                        Phase, ProvisionRequest, RunRequest, RuntimeEnrollment, StartPermit)


INTERFACE_VERSION = "trusted-checker-runtime-boundary-v1"


class RuntimeDockerAdapterV1(Protocol):
    def observe_daemon(self, intent: CreateIntent) -> Attestation: ...
    def create_target(self, intent: CreateIntent, permit: DispatchPermit) -> Attestation: ...
    def create_runner(self, intent: CreateIntent, permit: DispatchPermit) -> Attestation: ...
    def observe_target(self, enrollment: RuntimeEnrollment, context_uuid: str, phase: Phase) -> Attestation: ...
    def start_runner(self, permit: StartPermit) -> None: ...
    def start_new_owned_target(self, provisioning_uuid: str, ownership_receipt_digest: str) -> None: ...


class RuntimeAuthorityV1(Protocol):
    def register_approval(self, signed: Attestation) -> str: ...
    def provision(self, request: ProvisionRequest) -> CreateIntent: ...
    def begin_create(self, intent: CreateIntent, daemon_receipt: Attestation) -> DispatchPermit: ...
    def record_create_response(self, permit: DispatchPermit, signed: Attestation) -> str: ...
    def enroll(self, provisioning_uuid: str) -> RuntimeEnrollment: ...
    def reserve_run(self, request: RunRequest, enrollment: RuntimeEnrollment) -> str: ...
    def authorize_start(self, run_uuid: str) -> StartPermit: ...
    def revoke_binding(self, enrollment: RuntimeEnrollment) -> None: ...
    def kill(self) -> None: ...


class TrustedHTTPRunnerV1(Protocol):
    # A runner implementation uses a fixed immutable policy and bounded protocol;
    # it cannot itself produce an authenticated control-plane receipt/key.
    def bounded_http_result(self, enrollment: RuntimeEnrollment) -> bytes: ...


class RuntimeShadowBackendV1(Protocol):
    def observe_owned_runner(self, shadow_run_uuid: str) -> Attestation: ...
    def collect_validated_probe(self, shadow_run_uuid: str) -> Attestation: ...


class EgressEnforcerV1(Protocol):
    def attest_installed_rules(self, enrollment: RuntimeEnrollment, context_uuid: str, phase: Phase) -> Attestation: ...


class IndependentEgressValidatorV1(Protocol):
    def validate_readback_and_peer_matrix(self, enforcement: Attestation) -> Attestation: ...


class CleanupRecoveryAgentV1(Protocol):
    # Receives only a known immutable ownership reference; no candidate/name/label
    # discovery, generic remove, target adoption, force or start method.
    def confirm_known_ownership_cleanup(self, ownership_receipt_digest: str) -> Attestation: ...


class OrdinaryMetadataReaderV1(Protocol):
    # No Django connection/model/queryset or write method is exposed by this port.
    def read(self, attempt: AttemptReference) -> OrdinaryMetadata: ...
