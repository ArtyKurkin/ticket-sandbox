"""Explicit v2 ports for the live composition; v1 offline interfaces stay unchanged.

The authority owns permit allocation, so create(intent) performs the existing v1
begin_create/fence/response protocol internally rather than accepting raw SDK args.
"""
from typing import Protocol
from trusted_checker_runtime.attestation import Attestation
from trusted_checker_runtime.contracts import CreateIntent, Phase, RuntimeEnrollment, StartPermit
from trusted_checker_runtime.interfaces import RuntimeAuthorityV1

INTERFACE_VERSION = 'trusted-checker-live-runtime-v2'


class RuntimeAuthorityV2(RuntimeAuthorityV1, Protocol):
    def runner_create_intent(self, run_uuid: str) -> CreateIntent: ...
    def record_runner_finished(self, run_uuid: str, signed: Attestation) -> None: ...


class RuntimeDockerAdapterV2(Protocol):
    def create(self, intent: CreateIntent) -> Attestation: ...
    def start_target(self, provisioning_uuid: str) -> None: ...
    def observe_target(self, enrollment: RuntimeEnrollment, context_uuid: str, phase: Phase) -> Attestation: ...
    def observe_owned_runner(self, run_uuid: str) -> Attestation: ...
    def start_runner(self, permit: StartPermit) -> None: ...
    def release_and_collect(self, run_uuid: str, enrollment: RuntimeEnrollment) -> Attestation: ...
    def finish_runner(self, run_uuid: str) -> None: ...


class ActiveNamespaceProbeProviderV2(Protocol):
    # Exact keys/cases/types/binding/time are validated independently by egress.py.
    # Requires protected contemporaneous packet evidence, never caller booleans.
    def measure(self, approval, target, runner, ports) -> tuple[dict, ...]: ...
